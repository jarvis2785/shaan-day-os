export default function BottomNav() {
  const pathname = usePathname();

  if (isAuthRoute(pathname)) return null;

  return (
    <nav
      className="fixed bottom-0 left-0 right-0 z-50"
      style={{
        backgroundColor: '#1C1C1E',
        borderTop: '1px solid #2C2C2E',
      }}
    >
      <div className="max-w-app mx-auto flex items-center justify-around h-16 pb-safe">
        {tabs.map((tab) => {
          const active = pathname === tab.href;
          return (
            <Link
              key={tab.href}
              href={tab.href}
              className="flex flex-col items-center justify-center gap-1 min-w-[64px] h-full relative"
            >
              <motion.div
                style={{ color: active ? '#30D158' : '#48484A' }}
                animate={{ scale: active ? 1.15 : 1 }}
                transition={{ type: 'spring', stiffness: 400, damping: 20 }}
              >
                {tab.icon}
              </motion.div>
              {active && (
                <>
                  <span className="text-[10px] font-medium" style={{ color: '#30D158' }}>
                    {tab.label}
                  </span>
                  <motion.div
                    className="absolute bottom-1 w-1 h-1 rounded-full"
                    style={{ backgroundColor: '#30D158' }}
                    layoutId="nav-dot"
                  />
                </>
              )}
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
